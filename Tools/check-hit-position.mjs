import assert from 'node:assert/strict';
import {hitPositionOffsets,hitPositionPlan,updateSnapBinding,snapBindingNeedsSelfState,prepareHitPosition,consumeHitPositionOffsets} from '../Engine/hit-position.js';

const base={origin:[100,10,0],target:[120,20,0],facing:1};
assert.deepEqual(prepareHitPosition({snap:'var(8),,0,4.9',mindist:'5',maxdist:'8'},{splitPair:value=>value.split(','),evaluate:value=>value==='var(8)'?30:Number(value)}),{snap:[30,undefined,0],snapTime:4,minDistance:[5],maxDistance:[8]});
assert.deepEqual(prepareHitPosition({},{splitPair:value=>value.split(','),evaluate:Number}),{snap:[],snapTime:0,minDistance:[],maxDistance:[]});
assert.equal(prepareHitPosition({snap:'0,0,0,16777217'},{splitPair:value=>value.split(','),evaluate:Number}).snapTime,16777217);
assert.deepEqual(hitPositionOffsets(base),[0,0,0]);
assert.deepEqual(hitPositionOffsets({...base,snap:[30,-5]}),[10,-15,0]);
assert.deepEqual(hitPositionOffsets({...base,facing:-1,snap:[30,-5]}),[-50,-15,0]);
assert.deepEqual(hitPositionOffsets({...base,minDistance:[30],maxDistance:[50]}),[10,0,0]);
assert.deepEqual(hitPositionOffsets({...base,minDistance:[10],maxDistance:[15]}),[-5,0,0]);
assert.deepEqual(hitPositionOffsets({...base,snap:[30,-5],guarded:true}),[10,0,0]);
assert.deepEqual(hitPositionOffsets({...base,snap:[30,-5],guarded:true,aerial:true}),[10,-15,0]);
assert.deepEqual(hitPositionOffsets({...base,snap:[30],scaleRatio:2}),[140,0,0]);
const fighter={x:10,y:20,moveType:'I',getHit:{xoff:3,yoff:-5,zoff:0}};
assert.equal(consumeHitPositionOffsets(fighter),false);
fighter.moveType='H';assert.equal(consumeHitPositionOffsets(fighter),true);
assert.deepEqual([fighter.x,fighter.y],[13,15]);
consumeHitPositionOffsets(fighter);assert.deepEqual([fighter.x,fighter.y],[13,15]);
const bindingPlan=hitPositionPlan({...base,snap:[30,-5],snapTime:2});
assert.deepEqual(bindingPlan.binding,{remaining:3,offsets:[30,-5,null]});
const bound={x:120,y:20,moveType:'H',vx:9,vy:9,getHit:{xoff:10,yoff:-15},snapBinding:bindingPlan.binding};
const binder={x:100,y:10,facing:1,vx:3,vy:-2};
updateSnapBinding(bound,binder,{copyVelocity:true,binderPaused:true});
assert.deepEqual([bound.x,bound.y,bound.vx,bound.vy,bound.snapBinding.remaining],[130,5,3,-2,3]);
binder.x=110;binder.facing=-1;updateSnapBinding(bound,binder);
assert.deepEqual([bound.x,bound.y,bound.snapBinding.remaining],[80,5,2]);
updateSnapBinding(bound,binder);updateSnapBinding(bound,binder);
assert.equal(bound.snapBinding.remaining,0);
assert.equal(updateSnapBinding(bound,binder),false);assert.equal(bound.snapBinding,null);
const indefinite=hitPositionPlan({...base,snap:[30],snapTime:-1}).binding;
bound.snapBinding=indefinite;updateSnapBinding(bound,binder);updateSnapBinding(bound,binder);
assert.equal(bound.snapBinding.remaining,-1);
assert.equal(updateSnapBinding(bound,null),false);assert.equal(bound.snapBinding,null);
assert.equal(hitPositionPlan({...base,snap:[30],snapTime:2,binderPaused:true}).binding.remaining,2);
assert.deepEqual(hitPositionPlan({...base,snap:[30,-5],snapTime:2,guarded:true}).binding.offsets,[30,null,null]);
assert.equal(snapBindingNeedsSelfState({remaining:2},binder,{binderWasHit:true}),true);
assert.equal(snapBindingNeedsSelfState({remaining:2},null),true);
assert.equal(snapBindingNeedsSelfState({remaining:-1},binder,{binderWasHit:true}),false);
assert.equal(snapBindingNeedsSelfState({remaining:0},null),false);
console.log('Pinned HitDef distance/snap offsets, facing, scale and guarded-Y rules passed');
