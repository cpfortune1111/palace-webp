import assert from 'node:assert/strict';
import {applyClsnOverrideController,createClsnOverrides,overriddenClsnBoxes} from '../Engine/clsn-override.js';
const caller={coord:320,slots:createClsnOverrides()},recipient={coord:640,slots:createClsnOverrides()};
const api={evaluate:Number,findActor:id=>id===2?recipient:null,localCoord:actor=>actor.coord,split:value=>String(value).split(','),slots:actor=>actor.slots};
applyClsnOverrideController({type:'OverrideClsn',params:{redirectid:2,group:'dummy',index:99,rect:'20,10,-10,-30'}},caller,api);
assert.deepEqual(overriddenClsnBoxes([],recipient.slots[3]),[[-20,-60,40,20]]);
applyClsnOverrideController({type:'OverrideClsn',params:{group:'all',index:-1,rect:'1,2,3,4'}},caller,api);
assert.equal(caller.slots.every(slot=>slot.length===1),true);
assert.deepEqual(overriddenClsnBoxes([],caller.slots[3]),[]);
const original=[[0,0,10,10],[20,20,30,30]];
assert.deepEqual(overriddenClsnBoxes(original,[{index:0,rect:[0,0,0,0]}]),[[20,20,30,30]]);
assert.deepEqual(overriddenClsnBoxes(original,[{index:-1,rect:[0,0,0,0]}]),[]);
assert.deepEqual(overriddenClsnBoxes(original,[{index:99,rect:[1,2,3,4]}]),[...original,[1,2,3,4]]);
assert.deepEqual(overriddenClsnBoxes(original,caller.slots[0]),[[1,2,3,4],[1,2,3,4]]);
assert.deepEqual(original,[[0,0,10,10],[20,20,30,30]]);
applyClsnOverrideController({type:'OverrideClsn',params:{}},caller,api);
assert.equal(caller.slots.every(slot=>slot.length===0),true);
applyClsnOverrideController({type:'OverrideClsn',params:{redirectid:99,rect:'invalid'}},caller,api);
console.log('Native OverrideClsn defaults, all four groups, signed redirection, deletion, append and immutable geometry passed');
