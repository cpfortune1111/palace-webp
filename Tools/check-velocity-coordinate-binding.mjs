import assert from 'node:assert/strict';
import {velocityCoordinateBinding} from '../Engine/velocity-coordinate-binding.js';
import {applyVelocityController} from '../Engine/velocity-controllers.js';

const actor={vx:8,vy:-16,facing:-1,getHit:{xvel:12,yvel:-8,damage:7}},target={vx:0,vy:0,facing:1,getHit:{}};
const source=velocityCoordinateBinding(actor,4),recipient=velocityCoordinateBinding(target,2),api={evaluate:Number,findActor:id=>id===2?recipient:null};
assert.deepEqual([source.vx,source.vy,source.localScale],[2,-4,4]);
applyVelocityController({type:'VelSet',params:{x:2.75,y:-4}},source,api);
assert.deepEqual([actor.vx,actor.vy],[11,-16]);
applyVelocityController({type:'VelAdd',params:{redirectid:2,x:3,y:-2}},source,api);
assert.deepEqual([target.vx,target.vy],[12,-8]);
applyVelocityController({type:'VelMul',params:{redirectid:2,x:.5,y:2}},source,api);
assert.deepEqual([target.vx,target.vy],[6,-16]);
applyVelocityController({type:'HitVelSet',params:{x:1,y:1}},source,api);
assert.deepEqual([actor.vx,actor.vy],[-12,-8]);
assert.equal(source.getHit.damage,7);
assert.deepEqual(actor.getHit,{xvel:12,yvel:-8,damage:7});
assert.equal(velocityCoordinateBinding(null,4),null);
assert.throws(()=>velocityCoordinateBinding(actor,0),/Invalid velocity/);
console.log('Velocity world/local bridge preserves redirected scales, dimensionless multipliers and existing hit velocities');
actor.vz=12;target.vz=0;actor.getHit.zvel=16;
applyVelocityController({type:'VelSet',params:{z:3}},source,api);
assert.equal(actor.vz,12);
applyVelocityController({type:'VelAdd',params:{redirectid:2,z:2}},source,api);
assert.equal(target.vz,8);
applyVelocityController({type:'VelMul',params:{redirectid:2,z:-.5}},source,api);
assert.equal(target.vz,-4);
applyVelocityController({type:'HitVelSet',params:{z:1}},source,api);
assert.equal(actor.vz,16);
console.log('Velocity Z uses the same bridge without facing or duplicate recipient evaluation');
