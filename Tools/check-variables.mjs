import assert from 'node:assert/strict';
import {applyVariableController} from '../Engine/variables.js';

const binding={vars:Array(60).fill(0),fvars:Array(40).fill(0),sysvars:Array(10).fill(0),sysfvars:Array(5).fill(0)};
const evaluate=expression=>expression==='index'?3:Number(expression);
for(const [kind,storage] of [['var','vars'],['fvar','fvars'],['sysvar','sysvars'],['sysfvar','sysfvars']]){
 const floating=kind.includes('fvar');
 assert.equal(applyVariableController({type:'VarSet',params:{target:kind+'(index)',value:'2.75'}},binding,evaluate),true);
 assert.equal(binding[storage][3],floating?2.75:2);
 applyVariableController({type:'VarAdd',params:{target:kind+'(3)',value:'-1.5'}},binding,evaluate);
 assert.equal(binding[storage][3],floating?1.25:1);
 applyVariableController({type:'VarSet',params:{target:kind+'(-1)',value:'7'}},binding,evaluate);
 assert.equal(binding[storage][-1],undefined);
}
applyVariableController({type:'varset',params:{fv:'2',value:'3.5'}},binding,evaluate);
assert.equal(binding.fvars[2],3.5);
applyVariableController({type:'varset',params:{v:'2',value:'3.5'}},binding,evaluate);
assert.equal(binding.vars[2],3);
applyVariableController({type:'VarRangeSet',params:{first:'1',last:'3',value:'7.9'}},binding,evaluate);
assert.deepEqual(binding.vars.slice(1,4),[7,7,7]);
applyVariableController({type:'VarRangeSet',params:{fvalue:'2.5'}},binding,evaluate);
assert.ok(binding.fvars.every(value=>value===2.5));
applyVariableController({type:'VarRangeSet',params:{first:'-1',last:'3',value:'8'}},binding,evaluate);
assert.equal(binding.vars[1],7);
const redirected={vars:Array(60).fill(0),fvars:Array(40).fill(0)};
applyVariableController({type:'VarRangeSet',params:{redirectid:'2',value:'9'}},binding,evaluate,{findActor:()=>redirected});
assert.ok(redirected.vars.every(value=>value===9));assert.equal(binding.vars[1],7);
applyVariableController({type:'VarRandom',params:{v:'2',range:'5,9'}},binding,evaluate,{random:()=>0.999999});
assert.equal(binding.vars[2],9);
let randomCalls=0;const randomOrder=[];
for(const index of [-1,60])applyVariableController({type:'VarRandom',params:{v:String(index),range:'5,9'}},binding,expression=>{randomOrder.push(expression);return Number(expression)},{random:()=>{randomCalls++;randomOrder.push('random');return .5}});
assert.equal(randomCalls,2);assert.deepEqual(randomOrder,['-1','5','9','random','60','5','9','random']);assert.equal(binding.vars[-1],undefined);assert.equal(binding.vars[60],undefined);
applyVariableController({type:'VarRandom',params:{redirectid:'99',v:'0',range:'5,9'}},binding,evaluate,{findActor:()=>null,random:()=>{randomCalls++;return 0}});assert.equal(randomCalls,2);
applyVariableController({type:'VarSet',params:{v:'0',value:'2147483647'}},binding,evaluate);
applyVariableController({type:'VarAdd',params:{v:'0',value:'1'}},binding,evaluate);
assert.equal(binding.vars[0],-2147483648);
const sparse={vars:{},fvars:{}};
applyVariableController({type:'VarSet',params:{v:'9000',value:'2'}},sparse,evaluate,{compatibility:'ikemen'});
assert.equal(sparse.vars[9000],2);
applyVariableController({type:'VarRangeSet',params:{first:'100',last:'5000',value:'3'}},sparse,evaluate,{compatibility:'ikemen'});
assert.equal(sparse.vars[2599],3);assert.equal(sparse.vars[2600],undefined);
applyVariableController({type:'VarRangeSet',params:{last:'2147483647',value:'0'}},sparse,evaluate,{compatibility:'ikemen'});
assert.deepEqual(sparse.vars,{});
const parent={kind:'helper',vars:Array(60).fill(0),fvars:Array(40).fill(0)};
const child={kind:'helper',vars:Array(60).fill(0),fvars:Array(40).fill(0)};
const owners={parentActor:actor=>actor===child?parent:null,rootActor:actor=>actor.kind==='helper'?binding:null,findActor:id=>id===3?child:null};
applyVariableController({type:'ParentVarSet',params:{v:'4',value:'12'}},child,evaluate,owners);
assert.equal(parent.vars[4],12);assert.equal(child.vars[4],0);assert.equal(binding.vars[4],0);
applyVariableController({type:'ParentVarAdd',params:{fv:'1',value:'2.75'}},child,evaluate,owners);
assert.equal(parent.fvars[1],2.75);
applyVariableController({type:'RootVarSet',params:{v:'4',value:'20'}},child,evaluate,owners);
assert.equal(binding.vars[4],20);assert.equal(parent.vars[4],12);
applyVariableController({type:'RootVarAdd',params:{fv:'1',value:'1.5'}},child,evaluate,owners);
assert.equal(binding.fvars[1],4);
applyVariableController({type:'ParentVarSet',params:{redirectid:'3',v:'4',value:'24'}},binding,evaluate,owners);
assert.equal(parent.vars[4],24);
owners.parentActor=()=>null;
applyVariableController({type:'ParentVarAdd',params:{v:'4',value:'5'}},child,evaluate,owners);
assert.equal(parent.vars[4],24);
assert.equal(applyVariableController({type:'Null'},binding,evaluate),false);
console.log('Variable types, native targets, expression indices and bounds passed');
