import assert from 'node:assert/strict';
import {applyModifyReflection,createReflectionOverride,resetReflectionOverride,reflectionAngleState,reflectionPaletteEffect} from '../Engine/modify-reflection.js';

const caller={scale:1,state:createReflectionOverride()},target={scale:.25,state:createReflectionOverride()},samples=[];
const api={evaluate:expression=>{samples.push(expression);return expression==='undefined'?NaN:expression==='string'?'12':Number(expression)},findActor:id=>id===2?target:null,state:actor=>actor.state,localScale:actor=>actor.scale,split:expression=>String(expression).split(',')};
assert.equal(applyModifyReflection({type:'Null'},caller,api),false);
applyModifyReflection({type:'ModifyReflection',params:{redirectid:2,intensity:300,offset:'3,-2',xscale:2,yscale:-3}},caller,api);
assert.deepEqual(target.state,{...createReflectionOverride(),intensity:255,offset:[12,-8],xscale:2,yscale:-3});
assert.deepEqual(caller.state,createReflectionOverride());
assert.deepEqual(samples,[2,300,'3','-2',2,-3]);
applyModifyReflection({type:'ModifyReflection',params:{redirectid:2,offset:'5'}},caller,api);
assert.deepEqual(target.state.offset,[20,-8]);
applyModifyReflection({type:'ModifyReflection',params:{redirectid:2,intensity:'string',xscale:'undefined'}},caller,api);
assert.equal(target.state.intensity,0);assert.equal(target.state.xscale,0);
const before=samples.length;
applyModifyReflection({type:'ModifyReflection',params:{redirectid:999,offset:'1,2'}},caller,api);
assert.deepEqual(samples.slice(before),[999]);
assert.throws(()=>applyModifyReflection({type:'ModifyReflection',params:{window:'1,2,3,4'}},caller,api),/not implemented/);
assert.throws(()=>applyModifyReflection({type:'ModifyReflection',params:{offset:'1,2,3'}},caller,api),/at most two/);
resetReflectionOverride(target.state);
assert.deepEqual(target.state,createReflectionOverride());
applyModifyReflection({type:'ModifyReflection',params:{intensity:123,ignorehitpause:1,persistent:0}},caller,api);
assert.equal(caller.state.intensity,123);
assert.equal(applyModifyReflection({type:'ModifyReflection',params:{}},{kind:'helper'},{...api,state:()=>{throw Error('Unexpected empty-controller storage lookup')}}),true);
const base={enabled:true,value:30,xangle:5,yangle:10,scale:[2,3],pivot:[4,5]},override={...createReflectionOverride(),angle:20,xangle:3,yangle:4};
for(const facing of [1,-1]){
 assert.deepEqual(reflectionAngleState(base,override,{},facing),{enabled:true,value:50,xangle:8,yangle:14,scale:[2,3],pivot:[4,5]});
 assert.deepEqual(reflectionAngleState(base,{...override,keeptransform:false},{angle:90},facing),{enabled:true,value:20*facing,xangle:3,yangle:4*facing,scale:[2,3],pivot:[4,5]});
}
assert.equal(reflectionAngleState({...base,value:-30},override,{},1).value,-50);
assert.equal(reflectionAngleState(base,createReflectionOverride(),{angle:15},1).value,45);
assert.equal(reflectionAngleState(base,{...createReflectionOverride(),keeptransform:false},{angle:15},1).value,0);
const angularStart=samples.length;
applyModifyReflection({type:'ModifyReflection',params:{redirectid:2,intensity:100,keeptransform:0,offset:'1,2',xscale:3,yscale:4,angle:5,xangle:6,yangle:7}},caller,api);
assert.deepEqual(samples.slice(angularStart),[2,100,0,'1','2',3,4,5,6,7]);
assert.deepEqual([target.state.keeptransform,target.state.angle,target.state.xangle,target.state.yangle],[false,5,6,7]);
applyModifyReflection({type:'ModifyReflection',params:{color:'999,-1,128'}},caller,api);
assert.deepEqual(caller.state.color,[255,0,128]);
applyModifyReflection({type:'ModifyReflection',params:{color:'64'}},caller,api);
assert.deepEqual(caller.state.color,[64,0,0]);
const palette={add:[1,2,3],mul:[256,128,512],color:1,hue:0,invertall:false,invertblend:0,allowNegative:false};
assert.equal(reflectionPaletteEffect(palette,createReflectionOverride(),{}),palette);
const tinted=reflectionPaletteEffect(palette,{...createReflectionOverride(),color:[255,128,0]},{});
assert.deepEqual(tinted.mul,[256,64,0]);
assert.deepEqual(palette.mul,[256,128,512]);
assert.notEqual(tinted.add,palette.add);
assert.deepEqual(reflectionPaletteEffect(null,{...createReflectionOverride(),color:[0,0,0]},{}).mul,[0,0,0]);
assert.deepEqual(reflectionPaletteEffect(palette,createReflectionOverride(),{color:0xff8000}).mul,[256,64,0]);
target.state.color=[9,8,7];
const colorReads=[];
applyModifyReflection({type:'ModifyReflection',params:{redirectid:2,color:'red,green,blue',intensity:'alpha'}},caller,{...api,evaluate:expression=>{if(typeof expression==='number')return expression;colorReads.push([...target.state.color]);return {red:1,green:2,blue:3,alpha:4}[expression]}});
assert.deepEqual(colorReads,[[9,8,7],[9,8,7],[9,8,7],[1,2,3]]);
console.log('ModifyReflection supported operands preserve native clamps, signed scales, caller redirection scope, coordinate ratio, omitted components and transient defaults');
