import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {applyHelperSizeOverrides,helperSizeDrawing,projectileSpriteScale,sizeCollisionConstants,sizeConstant,sizeConstantNames} from '../Engine/size-constants.js';
import {sizeCollisionBox} from '../Engine/size-collision-box.js';

const audit=JSON.parse(readFileSync(new URL('../Docs/CONST-AUDIT.json',import.meta.url),'utf8'));
assert.deepEqual([...sizeConstantNames].sort(),audit.rows.filter(row=>row.name.startsWith('size.')&&!/^size\.(proj\.)?attack\.dist(?:\.|$)/.test(row.name)).map(row=>row.name).sort());
assert.equal(sizeConstantNames.size,21);
const {sizeDefinition:definition}=JSON.parse(readFileSync(new URL('./fixtures/size-definition.json',import.meta.url),'utf8'));
const expected={'size.xscale':1.5,'size.yscale':.75,'size.ground.back':21,'size.ground.front':31,'size.air.back':13,'size.air.front':15,'size.height':110,'size.attack.depth.top':7,'size.attack.depth.bottom':8,'size.proj.doscale':2,'size.head.pos.x':-5,'size.head.pos.y':-300,'size.mid.pos.x':-3,'size.mid.pos.y':-200,'size.shadowoffset':9,'size.draw.offset.x':6,'size.draw.offset.y':-7,'size.depth.top':10,'size.depth.bottom':11,'size.weight':123,'size.pushfactor':Math.fround(.8)};
const unscaled=new Set(['size.xscale','size.yscale','size.proj.doscale','size.weight','size.pushfactor']);
for(const [name,value]of Object.entries(expected)){
 assert.deepEqual(sizeConstant(name.toUpperCase(),definition),{handled:true,value});
 assert.equal(sizeConstant(name,definition,{subjectLocalCoord:1280,expressionLocalCoord:320}).value,unscaled.has(name)?value:Math.fround(value/4));
}
assert.deepEqual(sizeConstant('size.attack.dist',definition),{handled:false});
assert.deepEqual(sizeConstant('size.height'),{handled:false});
assert.throws(()=>sizeConstant('size.height',definition,{subjectLocalCoord:0}),/coordinates/);
const params={'size.xscale':'1.25','size.yscale':'.5','size.ground.back':'var(1)','size.ground.front':'37','size.air.back':'18','size.air.front':'38','size.height':'222','size.proj.doscale':'3.9','size.head.pos':'-9','size.mid.pos':'-10,20','size.shadowoffset':'-11','size.depth':'20','size.weight':'88.9','size.pushfactor':'1.2'};
const api={evaluate:value=>value==='var(1)'?17:Number(value),split:value=>String(value).split(',')};
const child=applyHelperSizeOverrides(definition,params,api);
assert.deepEqual(child.standbox,[-17,-222,37,4]);
assert.deepEqual(child.airbox,[-18,-90,38,0]);
assert.deepEqual(child.crouchbox,definition.crouchbox);
assert.deepEqual(child.downbox,definition.downbox);
assert.deepEqual(child.headPosition,[-9,-300]);
assert.deepEqual(child.midPosition,[-10,20]);
assert.deepEqual(child.depth,[20,11]);
assert.deepEqual([child.xscale,child.yscale,child.projectileDoScale,child.shadowOffset,child.weight,child.pushFactor],[1.25,.5,3,-11,88,Math.fround(1.2)]);
child.attackDistance.x[0]=999;
assert.equal(definition.attackDistance.x[0],240);
assert.equal(definition.standbox[0],-21);
assert.throws(()=>applyHelperSizeOverrides(definition,{'size.head.pos':'1,2,3'},api),/at most two/);
const collision=sizeCollisionConstants(child);
assert.deepEqual(sizeCollisionBox(collision,'S'),[-17,-222,37,4]);
assert.deepEqual(sizeCollisionBox(collision,'C'),[-25,-50,26,4]);
assert.deepEqual(sizeCollisionBox(collision,'A'),[-18,-90,38,0]);
collision['size.stand.sizebox'][0]=99;
assert.equal(child.standbox[0],-17);
assert.deepEqual(helperSizeDrawing(child,{localCoord:640,worldWidth:1280,facing:-1}),{scale:[2.5,1],offset:[-12,-14]});
assert.deepEqual(helperSizeDrawing(),{scale:[1,1],offset:[0,0]});
assert.throws(()=>helperSizeDrawing(child,{localCoord:0}),/coordinates/);
const projectileApi={split:value=>String(value).split(','),evaluate:value=>value==='fvar(1)'?1.5:value==='1/4'?.25:Number(value)};
assert.deepEqual(projectileSpriteScale({},undefined,projectileApi),[1,1]);
assert.deepEqual(projectileSpriteScale({projscale:'2'},undefined,projectileApi),[2,1]);
assert.deepEqual(projectileSpriteScale({projscale:0},undefined,projectileApi),[0,1]);
const projectileOwner={xscale:2,yscale:.5,projectileDoScale:1};
assert.deepEqual(projectileSpriteScale({projscale:'fvar(1),1/4'},projectileOwner,projectileApi),[3,.125]);
assert.deepEqual(projectileSpriteScale({projscale:'fvar(1),1/4'},{...projectileOwner,projectileDoScale:0},projectileApi),[1.5,.25]);
assert.deepEqual(projectileSpriteScale({projscale:'fvar(1),1/4'},{...projectileOwner,projectileDoScale:-3},projectileApi),[3,.125]);
assert.deepEqual(projectileSpriteScale({projscale:'0'},projectileOwner,projectileApi),[0,.5]);
assert.throws(()=>projectileSpriteScale({projscale:'1,2,3'},projectileOwner,projectileApi),/at most two/);
console.log('All remaining twenty-one Size names and fourteen Helper Size overrides preserve native boxes, components, copy isolation and units');
