import assert from 'node:assert/strict';
import {cancelProjectilePair,sortedProjectileCandidates,projectileTeamCanTrade} from '../Engine/projectile-cancellation.js';
const high={priority:7,remainingHits:1,params:{pausetime:'5,9'}},low={priority:6,remainingHits:1};
assert.deepEqual(cancelProjectilePair(high,low),[false,true]);
assert.equal(high.priorityPoints,6);assert.equal(high.remainingHits,1);assert.equal(high.hitPause,5);assert.equal(low.hitPause,0);
const multi={priority:1,remainingHits:2,params:{pausetime:'3,8'}},single={priority:1,remainingHits:1};
assert.deepEqual(cancelProjectilePair(multi,single),[false,true]);assert.equal(multi.remainingHits,1);assert.equal(multi.hitPause,3);
assert.deepEqual(cancelProjectilePair({priority:1,remainingHits:0},{priority:1,remainingHits:1}),[true,true]);
const candidates=[{id:3,x:4,y:0},{id:2,x:1,y:0},{id:1,x:-1,y:0}];
assert.deepEqual(sortedProjectileCandidates({x:0,y:0},candidates).map(value=>value.id),[1,2,3]);assert.equal(candidates[0].id,3);
console.log('Projectile cancellation priority-point depletion, hit counters, survivor pause and native distance/ID ordering passed');
const firstTeam={player:1},sameTeam={player:1},otherTeam={player:2};
assert.equal(projectileTeamCanTrade(firstTeam,sameTeam),false);
assert.equal(projectileTeamCanTrade(firstTeam,otherTeam),true);
assert.equal(projectileTeamCanTrade({...firstTeam,params:{affectteam:'B'}},sameTeam),true);
assert.equal(projectileTeamCanTrade({...firstTeam,params:{affectteam:'F'}},{...otherTeam,params:{affectteam:'F'}}),false);
assert.equal(projectileTeamCanTrade({...firstTeam,params:{affectteam:'F'}},{...sameTeam,params:{affectteam:'F'}}),true);
assert.equal(projectileTeamCanTrade({...firstTeam,params:{affectteam:'F'}},otherTeam),true);
assert.equal(projectileTeamCanTrade({...firstTeam,teamSide:7},{...otherTeam,teamSide:7}),false);
console.log('Native projectile team candidate rules distinguish Enemy/Friend/Both, mixed modes and team-side ownership');
